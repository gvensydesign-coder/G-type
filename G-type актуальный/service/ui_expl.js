/* один раз на (шрифт, начертание, параметр, диапазон): контуры минимума и максимума */
function xpData(key,lo,hi,txt,style){
  const k=[CUR_FONT,style,key,lo,hi,txt].join('|');
  let d=XP_CACHE.get(k);if(d)return d;
  const def=DEFAULTS,base=Object.assign({},def[style]||def.regular||DEFAULTS.regular);
  if(style==='italic'&&!(def.italic)){base.slant=base.slant||12;}
  let a=lo,b=hi;
  /* зона допустимых значений: за её пределами знаки ломаются (paramLimits), там превью бессмысленно */
  try{const r=paramLimits(Object.assign({},base));const L=r&&r.L&&r.L[key];if(L){a=Math.max(a,L[0]);b=Math.min(b,L[1]);if(b<=a){a=lo;b=hi;}}}catch(e){}
  try{d={a:xpRun(txt,Object.assign({},base,{[key]:a})),b:xpRun(txt,Object.assign({},base,{[key]:b}))};}catch(e){d=null;}
  if(XP_CACHE.size>300)XP_CACHE.clear();
  XP_CACHE.set(k,d);return d;
}
