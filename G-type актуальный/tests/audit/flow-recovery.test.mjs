import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {ensureServer, startChrome, openPage, sleep} from '../v96/lib.mjs';
const root=resolve(fileURLToPath(new URL('../..',import.meta.url)));
const server=await ensureServer(root);
const chrome=await startChrome();
const page=await openPage();
try {
  await page.send('Page.enable');
  await page.send('Page.addScriptToEvaluateOnNewDocument', {source:readFileSync(new URL('../../public/patches/flow-recovery.js',import.meta.url),'utf8')});
  await page.goto('home');
  await page.ev(`document.querySelector('#onb-skip')?.click()`);
  await page.ev(`document.querySelector('#flow-card').click()`);
  await page.ev(`(()=>{const n=document.querySelector('#fl-name');n.value='Мой шрифт Возврат';n.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('[data-a="method"][data-m="import"]').click();document.querySelector('[data-a="next"]').click()})()`);
  await page.send('Page.reload');
  await sleep(3000);
  const recovered = await page.ev(`(()=>{const f=GT_FLOW.FL;return {name:f.name,method:f.method,step:f.step,max:f.max,open:f.open}})()`);
  assert.deepEqual(recovered,{name:'Мой шрифт Возврат',method:'import',step:2,max:2,open:true});
  console.log('PASS: reload restores step 2, chosen name and import method');
  await page.ev(`document.querySelector('[data-a="openmode"]').click()`);
  await sleep(400);
  await page.ev(`(()=>{const svg='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000"><path d="M100 900 L500 100 L900 900 Z"/></svg>';const dt=new DataTransfer();dt.items.add(new File([svg],'А.svg',{type:'image/svg+xml'}));const input=document.querySelector('#imp-files');input.files=dt.files;input.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await sleep(1800);
  const sourceBefore = await page.ev(`JSON.stringify(IMP.glyphs['А'].c)`);
  await page.ev(`document.querySelector('#fl-chip').click()`);
  await page.send('Page.reload');
  await sleep(3000);
  assert.equal(await page.ev(`JSON.stringify(IMP.glyphs['А'].c)`),sourceBefore);
  assert.equal(await page.ev(`GT_FLOW.FL.started`),true);
  console.log('PASS: imported source contours remain unchanged after recovery');
  await page.ev(`GT_FLOW.go(4)`);
  await page.send('Page.reload');
  await sleep(3000);
  const guarded = await page.ev(`(()=>{const f=GT_FLOW.FL;return {step:f.step,max:f.max,dl:f.dl,text:document.querySelector('#fl-recovery-note').textContent}})()`);
  assert.equal(guarded.step,2); assert.equal(guarded.max,2); assert.equal(guarded.dl,null);
  assert.match(guarded.text,/соберите шрифт заново/);
  console.log('PASS: export stage returns to source validation without claiming a ready font');
  await page.ev(`GT_FLOW.end()`);
  await page.send('Page.reload');
  await sleep(3000);
  assert.equal(await page.ev(`GT_FLOW.FL.open`),false);
  console.log('PASS: an ended wizard does not reopen');
  await page.ev(`addEventListener('pagehide',()=>sessionStorage.setItem('gtype-flow-session-v1','{bad json'),{once:true})`);
  await page.send('Page.reload');
  await sleep(3000);
  assert.equal(await page.ev(`GT_FLOW.FL.open`),false);
  console.log('PASS: malformed recovery metadata does not interrupt startup');
} finally {page.close();chrome.kill();server?.kill();}

